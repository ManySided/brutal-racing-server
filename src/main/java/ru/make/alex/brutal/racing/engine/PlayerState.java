package ru.make.alex.brutal.racing.engine;

/**
 * Состояние игрока в комнате/гонке.
 * Хранится ТОЛЬКО в оперативной памяти сервера, НЕ сохраняется в БД.
 * Создаётся при подключении игрока к комнате, удаляется при дисконнекте.
 */
public class PlayerState {
    /**
     * Уникальный идентификатор игрока (UUID из JWT токена).
     * Используется для поиска игрока в комнате и отправки персональных данных.
     * Не меняется в течение сессии.
     */
    public final String playerId;

    /**
     * Логин игрока (отображаемое имя).
     * Передаётся клиентом при подключении к WebSocket.
     * Используется для отображения в таблице лидеров и списке игроков.
     */
    public final String login;

    // ========== ФИЗИКА МАШИНЫ ==========

    /**
     * Текущая полоса движения (0-3).
     * 0 = самая левая полоса, 3 = самая правая.
     * Меняется при нажатии кнопок MOVE_LEFT/MOVE_RIGHT.
     * Проверяется при столкновении с препятствиями и ракетами.
     */
    public int lane = 0;

    /**
     * Текущая скорость машины (условные единицы).
     * Растёт каждый тик игрового цикла в зависимости от:
     * - текущих оборотов (rpm) и зоны тахометра
     * - текущей передачи (gear)
     * - бонусов (например, сброс щита даёт +10)
     * Используется для расчёта дистанции и отображения на HUD.
     */
    public double speed = 0;

    /**
     * Пройденная дистанция (метры).
     * Растёт каждый тик: distance += speed / 10.0
     * Используется для:
     * - определения позиции в таблице лидеров
     * - проверки столкновений с препятствиями
     * - определения финиша (distance >= 5000)
     * - расчёта относительной позиции других игроков
     */
    public double distance = 0;

    /**
     * Обороты двигателя (0-100%).
     * Рассчитывается по формуле: rpm = (speed / (gear * 20.0)) * 100
     * Определяет ускорение:
     * - 0-30% (синяя зона): ускорение 0.5 (слабое)
     * - 30-70% (зелёная зона): ускорение 1.5 (оптимальное)
     * - 70-90% (жёлтая зона): ускорение 0.8 (среднее)
     * - 90-100% (красная зона): ускорение 0.2 (перегрев, риск взрыва)
     */
    public double rpm = 0;

    /**
     * Текущая передача (1-4).
     * Переключается кнопкой SHIFT_GEAR (циклически: 1→2→3→4→1).
     * Влияет на расчёт оборотов: чем выше передача, тем медленнее растут rpm.
     * Имеет кулдаун 1 секунда (античит).
     */
    public int gear = 1;

    // ========== СОСТОЯНИЕ ЖИЗНИ ==========

    /**
     * Флаг "жив ли игрок".
     * false означает, что игрок погиб (взорвался, врезался, сбит ракетой).
     * При false:
     * - игрок не получает обновления физики
     * - игрок не может отправлять команды
     * - отображается как "💀" в таблице лидеров
     * - машина меняет цвет на серый
     * Устанавливается в false при:
     * - столкновении с препятствием/ямой
     * - взрыве двигателя (rpm >= 95% более 1 секунды)
     * - попадании ракеты без щита
     * - дисконнекте игрока
     */
    public boolean isAlive = true;

    /**
     * Флаг "есть ли щит".
     * Щит защищает от одного попадания ракеты.
     * При попадании ракеты:
     * - если hasShield = true: щит поглощает урон, hasShield = false
     * - если hasShield = false: игрок взрывается
     * Можно сбросить кнопкой DROP_SHIELD:
     * - hasShield = false
     * - speed += 10 (бонус к скорости, машина стала легче)
     * - на трассе появляется препятствие SHIELD_OBSTACLE
     */
    public boolean hasShield = true;

    // ========== ЛОББИ (ФАЗА WAITING) ==========

    /**
     * Флаг "готов ли игрок к старту".
     * Устанавливается кнопкой "Я готов" в комнате ожидания.
     * Гонка может начаться только когда:
     * - минимум 2 игрока в комнате
     * - ВСЕ игроки нажали "Я готов" (isReady = true у всех)
     * - создатель комнаты нажал "Начать заезд"
     */
    public boolean isReady = false;

    // ========== ФИНИШ ==========

    /**
     * Флаг "финишировал ли игрок".
     * Устанавливается в true, когда distance >= 5000.
     * После финиша:
     * - игрок продолжает видеть гонку, но не может управлять
     * - отображается "ФИНИШ #N" в таблице лидеров
     * - машина не исчезает с трассы
     */
    public boolean finished = false;

    /**
     * Место на финише (1, 2, 3, 4).
     * Рассчитывается при финише: сколько игроков финишировали раньше.
     * Определяется по finishTime: кто раньше финишировал, то и место выше.
     */
    public int finishPosition = 0;

    /**
     * Тик (номер кадра), на котором игрок финишировал.
     * Используется для определения места: сравнивается с finishTime других игроков.
     * currentTick увеличивается каждый тик игрового цикла (30 раз в секунду).
     */
    public long finishTime = 0;

    // ========== СМЕРТЬ ==========

    /**
     * Причина смерти (для отображения на экране "Game Over").
     * Возможные значения:
     * - "COLLISION" - врезался в препятствие/яму/щит
     * - "ENGINE_EXPLOSION" - перегрел двигатель (rpm >= 95% более 1 сек)
     * - "ROCKET_HIT" - попал под ракету без щита
     * - "" (пустая строка) - связь потеряна (дисконнект)
     */
    public String deathReason = "";

    /**
     * Счётчик тиков в красной зоне (rpm >= 95%).
     * Увеличивается каждый тик, пока rpm >= 95.
     * Сбрасывается в 0, если rpm < 95.
     * Если explodeTime > 30 (1 секунда при 30 FPS) → взрыв двигателя.
     * Механика: игрок может кратковременно заходить в красную зону,
     * но если задержится надолго — двигатель не выдержит.
     */
    public int explodeTime = 0;

    // ========== ДЕТЕКЦИЯ ОБГОНОВ ==========

    /**
     * Предыдущая позиция в таблице лидеров (0, 1, 2, 3).
     * Используется для определения обгонов:
     * - если currentPosition < lastPosition → игрок кого-то обогнал
     * - отправляется событие "overtake" клиенту
     * Инициализируется -1 (не определена), обновляется каждый тик.
     */
    public int lastPosition = -1;

    // ========== АНТИЧИТ (КУЛДАУНЫ) ==========

    /**
     * Timestamp (в миллисекундах) последнего перемещения между полосами.
     * Кулдаун: 100 мс.
     * Защита от спама: игрок не может телепортироваться между полосами
     * чаще, чем 10 раз в секунду.
     */
    public long lastMoveTime = 0;

    /**
     * Timestamp последнего переключения передачи.
     * Кулдаун: 1000 мс (1 секунда).
     * Защита от спама: игрок не может переключать передачу
     * чаще, чем 1 раз в секунду.
     */
    public long lastGearShift = 0;

    /**
     * Timestamp последнего выстрела ракетой.
     * Кулдаун: 3000 мс (3 секунды).
     * Баланс: ракеты мощное оружие, но с долгим перезарядкой.
     */
    public long lastRocketTime = 0;

    // ========== КОНСТРУКТОР ==========

    /**
     * Создаёт начальное состояние игрока.
     * Вызывается при подключении игрока к комнате (GameRoom.addPlayer).
     *
     * @param playerId UUID игрока из JWT токена
     * @param login    логин игрока (отображаемое имя)
     */
    public PlayerState(String playerId, String login) {
        this.playerId = playerId;
        this.login = login;
    }
}
